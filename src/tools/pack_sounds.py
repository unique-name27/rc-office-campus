"""Pack the game's recorded sounds into src/js/sound-data.js (const SOUND_DATA), so the page needs no sound files.

usage: python -I src/tools/pack_sounds.py

Sources: src/assets/sounds/*.mp3 (CC0 recordings, see src/assets/sounds/CREDITS.md; made by src/tools/make_sounds.py).
Each file is stored as base64 under its name without the extension (e.g. "dog-bark-2").
"""
import base64, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', 'assets', 'sounds')
OUT = os.path.join(HERE, '..', 'js', 'sound-data.js')


def main():
    data = {}
    for f in sorted(os.listdir(SRC)):
        if f.endswith('.mp3'):
            data[f[:-4]] = base64.b64encode(open(os.path.join(SRC, f), 'rb').read()).decode()
    js = ('// generated by src/tools/pack_sounds.py from src/assets/sounds (CC0 recordings, see CREDITS.md there); do not edit by hand\n'
          'const SOUND_DATA=' + json.dumps(data, separators=(',', ':')) + ';\n')
    open(OUT, 'w', encoding='utf-8', newline='\n').write(js)
    print('wrote %s  %d sounds  %.1f KB' % (os.path.normpath(OUT), len(data), len(js) / 1024))


main()
